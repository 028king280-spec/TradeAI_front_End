// Helper to generate realistic intraday candle points for chart
function generateChartPoints(basePrice: number, count: number, trend: 'Bullish' | 'Bearish'): CandlePoint[] {
  const points: CandlePoint[] = [];
  let current = basePrice * 0.99;
  const vwapBase = basePrice * 0.992;
  const timeLabels = ['09:15', '09:30', '09:45', '10:00', '10:15', '10:30', '10:45', '11:00', '11:15', '11:30', '11:45', '12:00', '12:15', '12:30', '12:45', '13:00', '13:15', '13:30', '13:45', '14:00', '14:15', '14:30', '14:45', '15:00', '15:15', '15:30'];

  for (let i = 0; i < count; i++) {
    const delta = (Math.random() - (trend === 'Bullish' ? 0.42 : 0.58)) * (basePrice * 0.0035);
    current = Math.max(basePrice * 0.96, current + delta);
    const vwap = vwapBase + (current - vwapBase) * 0.65;
    const ema20 = current * 0.997;
    const ema50 = current * 0.993;
    const volume = Math.floor(45000 + Math.random() * 120000);

    points.push({
      time: timeLabels[i % timeLabels.length] || `T+${i}`,
      price: Number(current.toFixed(2)),
      vwap: Number(vwap.toFixed(2)),
      ema20: Number(ema20.toFixed(2)),
      ema50: Number(ema50.toFixed(2)),
      volume,
      support: Number((basePrice * 0.985).toFixed(2)),
      resistance: Number((basePrice * 1.015).toFixed(2)),
      expectedHigh: Number((basePrice * 1.016).toFixed(2)),
      expectedLow: Number((basePrice * 0.988).toFixed(2)),
    });
  }
  return points;
}

// Generate multi-timeframe chart data
function generateStockChartData(basePrice: number, trend: 'Bullish' | 'Bearish') {
  return {
    '1D': generateChartPoints(basePrice, 26, trend),
    '5D': generateChartPoints(basePrice * 0.98, 20, trend),
    '1M': generateChartPoints(basePrice * 0.95, 22, trend),
    '3M': generateChartPoints(basePrice * 0.92, 24, trend),
    '6M': generateChartPoints(basePrice * 0.88, 26, trend),
    '1Y': generateChartPoints(basePrice * 0.82, 30, trend),
  };
}

